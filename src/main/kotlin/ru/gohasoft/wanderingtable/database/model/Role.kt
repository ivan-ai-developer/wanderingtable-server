package ru.gohasoft.wanderingtable.database.model

/**
 * Роли пользователя. Пользователь может иметь несколько ролей одновременно
 * (например, быть игроком, создателем новостей и создателем турниров).
 *
 * Хранится как [jakarta.persistence.ElementCollection] со строковым представлением
 * ([jakarta.persistence.EnumType.STRING]) — порядок констант здесь менять безопасно.
 */
enum class Role {

    /** Заведующий клуба. Единственная роль, которая может выдавать и снимать роли. */
    CLUB_MANAGER,

    /** Базовая роль, выдаётся при регистрации: участие в событиях и создание заявок на партию. */
    PLAYER,

    /** Может публиковать новости клуба. */
    NEWS_CREATOR,

    /** Может добавлять настольные игры в справочник. */
    GAME_CREATOR,

    /** Может создавать турниры, чемпионаты и лиги. */
    TOURNAMENT_CREATOR
}
