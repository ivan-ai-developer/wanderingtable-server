package ru.gohasoft.wanderingtable.database.model.game

/**
 * Способ подсчёта результата в конкретной настольной игре.
 *
 * Задаётся на [Game] и определяет, какой подкласс `GameResult` принимается для партий
 * по этой игре: для «Манчкина» достаточно победы/поражения, для «Каркассона» нужны очки.
 */
enum class ResultType {

    /** Только исход: победа / поражение / ничья. */
    WIN_LOSS,

    /** Исход плюс набранные очки; победитель определяется по максимуму очков. */
    POINTS,

    /** Итоговое место в партии; первое место считается победой. */
    PLACEMENT
}
